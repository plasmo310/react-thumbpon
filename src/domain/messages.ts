export type MessageKey = keyof typeof englishMessages
export type Locale = 'ja' | 'en'

/** @param value 組み込みラベルが翻訳辞書にあるかを判定する */
export function isMessageKey(value: string): value is MessageKey {
  return Object.hasOwn(englishMessages, value)
}

/**
 * 原文と翻訳に共通する差し込み位置を置換する。ユーザーの入力は再翻訳しない。
 * @param locale 表示言語
 * @param key 日本語の原文
 * @param values 文中に差し込む値
 */
export function translate(locale: Locale, key: MessageKey, ...values: (string | number)[]): string {
  const message = locale === 'en' ? englishMessages[key] : key
  return message.replace(/\{(\d+)\}/g, (match, index) => String(values[Number(index)] ?? match))
}
